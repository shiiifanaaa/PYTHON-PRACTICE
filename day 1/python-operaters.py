# Arithmetic operators
a = 20
b = 10

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)

# Comparison operators
print(a > b)
print(a == b)

# Logical operators
print(a > 5 and b > 5)
print(a > 25 or b > 5)

# Assignment operators
x = 10
x += 5
print("Assignment:", x)

# Identity operators
a = [1, 2, 3]
b = a
c = [1, 2, 3]

print(a is b)
print(a is c)

# Membership operators
numbers = [10, 20, 30, 40]

print(20 in numbers)
print(50 not in numbers)
